/**
 * Converts a path to the posix format, so reports are stable across platforms.
 *
 * @param {string} value
 * @returns {string}
 */
const toPosix = (value) => value.split(path.sep).join('/');

/**
 * Creates the colorizer used by the report.
 *
 * @param {boolean} enabled
 * @returns {(color: keyof typeof COLORS, value: string) => string}
 */
function createPainter(enabled) {
  return (color, value) => (enabled ? `${COLORS[color]}${value}${COLORS.reset}` : value);
}

/**
 * Converts a small glob subset (`*`, `**`, `?`) into a RegExp.
 *
 * @param {string} glob
 * @returns {RegExp}
 */
function globToRegExp(glob) {
  const normalized = glob.replace(/\\/g, '/').replace(/^\.\//, '');
  let source = '';

  for (let index = 0; index < normalized.length; index++) {
    const char = normalized[index];

    if (char === '*') {
      if (normalized[index + 1] === '*') {
        index += 1;
        if (normalized[index + 1] === '/') {
          index += 1;
          source += '(?:.*/)?';
        } else {
          source += '.*';
        }
      } else {
        source += '[^/]*';
      }
      continue;
    }

    if (char === '?') {
      source += '[^/]';
      continue;
    }

    source += char.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }

  return new RegExp(`^${source}$`);
}

/**
 * @param {string} value
 * @returns {string}
 */
function formatBytes(value) {
  if (value < 1024) return `${value} B`;
  if (value < 1024 * 1024) return `${(value / 1024).toFixed(1)} KiB`;
  return `${(value / (1024 * 1024)).toFixed(2)} MiB`;
}

/**
 * Renders a buffer as `hex  |ascii|` so the difference is visible in the terminal.
 *
 * @param {Buffer} buffer
 * @returns {string}
 */
function formatBuffer(buffer) {
  if (buffer.length === 0) return '(empty)';

  const hex = [...buffer].map((byte) => byte.toString(16).padStart(2, '0')).join(' ');
  const ascii = [...buffer]
    .map((byte) => (byte >= 0x20 && byte <= 0x7e ? String.fromCharCode(byte) : '.'))
    .join('');

  return `${hex}  |${ascii}|`;
}

/**
 * @param {string} value
 * @param {number} max
 * @returns {string}
 */
function truncate(value, max = 160) {
  const single = value.replace(/\r?\n$/, '');
  return single.length > max ? `${single.slice(0, max)}…` : single;
}

/**
 * Replaces control characters so a binary line can be printed safely.
 *
 * @param {string} value
 * @returns {string}
 */
function sanitize(value) {
  // eslint-disable-next-line no-control-regex
  return value.replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, '·');
}

/**
 * @param {string} message
 * @returns {never}
 */
function usageError(message) {
  const error = new Error(message);
  error.name = 'UsageError';
  throw error;
}

/**
 * @param {string[]} argv
 * @returns {Options}
 */
function parseArgs(argv) {
  /** @type {Options} */
  const options = {
    reference: '',
    dist: 'dist',
    algorithm: 'sha256',
    ignore: [],
    includeMinJs: false,
    concurrency: 8,
    context: 24,
    contextLines: 3,
    diff: true,
    json: false,
    quiet: false,
    color: Boolean(process.stdout.isTTY) && !process.env.NO_COLOR,
    help: false,
  };

  /** @type {string[]} */
  const positional = [];

  for (let index = 0; index < argv.length; index++) {
    const arg = argv[index];

    /**
     * @param {string} name
     * @returns {string}
     */
    const readValue = (name) => {
      const value = argv[index + 1];
      if (value === undefined || value.startsWith('--')) usageError(`Missing value for ${name}.`);
      index += 1;
      return value;
    };

    switch (arg) {
      case '--help':
      case '-h':
        options.help = true;
        break;
      case '--dist':
        options.dist = readValue('--dist');
        break;
      case '--algorithm':
      case '--algo':
        options.algorithm = readValue('--algorithm');
        break;
      case '--ignore':
        options.ignore.push(readValue('--ignore'));
        break;
      case '--include-min-js':
        options.includeMinJs = true;
        break;
      case '--concurrency':
        options.concurrency = Number(readValue('--concurrency'));
        break;
      case '--context':
        options.context = Number(readValue('--context'));
        break;
      case '--context-lines':
        options.contextLines = Number(readValue('--context-lines'));
        break;
      case '--no-diff':
        options.diff = false;
        break;
      case '--json':
        options.json = true;
        break;
      case '--quiet':
        options.quiet = true;
        break;
      case '--no-color':
        options.color = false;
        break;
      default:
        if (arg.startsWith('-')) usageError(`Unknown option: ${arg}`);
        positional.push(arg);
    }
  }

  if (options.help) return options;

  if (positional.length === 0) {
    usageError(
      'You must inform the reference directory.\n\n  node build/verifyHash.mjs <referenceDir>',
    );
  }

  if (positional.length > 1) usageError(`Unexpected arguments: ${positional.slice(1).join(' ')}`);

  if (!Number.isFinite(options.concurrency) || options.concurrency < 1) {
    usageError('--concurrency must be a positive number.');
  }

  if (!Number.isFinite(options.context) || options.context < 0) {
    usageError('--context must be zero or a positive number.');
  }

  if (!Number.isFinite(options.contextLines) || options.contextLines < 0) {
    usageError('--context-lines must be zero or a positive number.');
  }

  options.reference = positional[0];
  options.ignore = options.ignore.map((pattern) => pattern.replace(/\\/g, '/'));

  if (!options.includeMinJs) {
    options.ignore.push(...DEFAULT_IGNORE_PATTERNS);
  }

  return options;
}

