/**
 * Recursively lists every file of a directory.
 *
 * @param {string} baseDir - Directory that will be scanned.
 * @param {RegExp[]} ignore - Patterns that must be skipped.
 * @returns {Promise<Map<string, FileEntry>>} Files indexed by their relative posix path.
 */
async function listFiles(baseDir, ignore) {
  /** @type {Map<string, FileEntry>} */
  const files = new Map();

  /**
   * @param {string} current
   * @returns {Promise<void>}
   */
  const visit = async (current) => {
    const entries = await fs.readdir(current, { withFileTypes: true });
    entries.sort((a, b) => a.name.localeCompare(b.name));

    for (const entry of entries) {
      const absolute = path.join(current, entry.name);
      const relative = toPosix(path.relative(baseDir, absolute));

      if (ignore.some((pattern) => pattern.test(relative))) continue;

      if (entry.isDirectory()) {
        // Folders such as `v1/build` are never part of the published output, so
        // they are pruned before being walked into.
        if (IGNORED_DIRECTORY_NAMES.has(entry.name.toLowerCase())) continue;
        await visit(absolute);
        continue;
      }

      // Symbolic links and special files are intentionally skipped: the goal is
      // to compare the real build output only.
      if (!entry.isFile()) continue;

      const stats = await fs.stat(absolute);
      files.set(relative, { absolute, size: stats.size });
    }
  };

  await visit(baseDir);

  return files;
}

/**
 * @param {string} absolutePath
 * @param {string} algorithm
 * @returns {Promise<string>} The hex digest of the file.
 */
function hashFile(absolutePath, algorithm) {
  return new Promise((resolve, reject) => {
    const hash = createHash(algorithm);
    const stream = createReadStream(absolutePath);

    stream.on('error', reject);
    stream.on('data', (chunk) => hash.update(chunk));
    stream.on('end', () => resolve(hash.digest('hex')));
  });
}

/**
 * Reads the first bytes of a file, used to sniff its content.
 *
 * @param {string} absolutePath
 * @param {number} [size=SNIFF_SIZE]
 * @returns {Promise<Buffer>}
 */
async function readHead(absolutePath, size = SNIFF_SIZE) {
  const handle = await fs.open(absolutePath, 'r');

  try {
    const buffer = Buffer.alloc(size);
    const { bytesRead } = await handle.read(buffer, 0, size, 0);
    return buffer.subarray(0, bytesRead);
  } finally {
    await handle.close();
  }
}

/**
 * A file is considered binary when a NUL byte shows up in its first bytes,
 * which is the same heuristic used by git and friends.
 *
 * @param {Buffer} buffer
 * @returns {boolean}
 */
function isBinaryBuffer(buffer) {
  return buffer.includes(0);
}

/**
 * Splits a text into lines, dropping the trailing empty entry caused by the
 * final newline and normalizing CRLF.
 *
 * @param {string} text
 * @returns {string[]}
 */
function splitLines(text) {
  if (text === '') return [];

  const lines = text.split('\n');

  if (lines[lines.length - 1] === '') lines.pop();

  return lines.map((line) => (line.endsWith('\r') ? line.slice(0, -1) : line));
}

/**
 * Classic LCS based diff. Returns the edit script that turns `oldLines` into
 * `newLines`.
 *
 * @param {string[]} oldLines
 * @param {string[]} newLines
 * @returns {{ type: 'equal' | 'add' | 'del', text: string }[]}
 */
function lcsDiff(oldLines, newLines) {
  const rows = oldLines.length;
  const columns = newLines.length;

  if (rows === 0) return newLines.map((text) => ({ type: 'add', text }));
  if (columns === 0) return oldLines.map((text) => ({ type: 'del', text }));

  const width = columns + 1;
  const table = new Uint32Array((rows + 1) * width);

  for (let row = rows - 1; row >= 0; row--) {
    for (let column = columns - 1; column >= 0; column--) {
      table[row * width + column] =
        oldLines[row] === newLines[column]
          ? table[(row + 1) * width + (column + 1)] + 1
          : Math.max(table[(row + 1) * width + column], table[row * width + (column + 1)]);
    }
  }

  /** @type {{ type: 'equal' | 'add' | 'del', text: string }[]} */
  const ops = [];
  let row = 0;
  let column = 0;

  while (row < rows && column < columns) {
    if (oldLines[row] === newLines[column]) {
      ops.push({ type: 'equal', text: oldLines[row] });
      row += 1;
      column += 1;
    } else if (table[(row + 1) * width + column] >= table[row * width + (column + 1)]) {
      ops.push({ type: 'del', text: oldLines[row] });
      row += 1;
    } else {
      ops.push({ type: 'add', text: newLines[column] });
      column += 1;
    }
  }

  while (row < rows) ops.push({ type: 'del', text: oldLines[row++] });
  while (column < columns) ops.push({ type: 'add', text: newLines[column++] });

  return ops;
}

/**
 * Builds the edit script of two files, trimming the common prefix/suffix first
 * so the LCS table stays small on big files.
 *
 * @param {string[]} oldLines
 * @param {string[]} newLines
 * @returns {{ type: 'equal' | 'add' | 'del', text: string }[]}
 */
function computeLineDiff(oldLines, newLines) {
  let start = 0;
  while (
    start < oldLines.length &&
    start < newLines.length &&
    oldLines[start] === newLines[start]
  ) {
    start += 1;
  }

  let oldEnd = oldLines.length;
  let newEnd = newLines.length;

  while (oldEnd > start && newEnd > start && oldLines[oldEnd - 1] === newLines[newEnd - 1]) {
    oldEnd -= 1;
    newEnd -= 1;
  }

  /** @type {{ type: 'equal' | 'add' | 'del', text: string }[]} */
  const ops = [];

  for (let index = 0; index < start; index++) {
    ops.push({ type: 'equal', text: oldLines[index] });
  }

  const middleOld = oldLines.slice(start, oldEnd);
  const middleNew = newLines.slice(start, newEnd);

  if (middleOld.length * middleNew.length > MAX_LCS_CELLS) {
    // Too big to run the LCS: report the whole block as replaced.
    for (const text of middleOld) ops.push({ type: 'del', text });
    for (const text of middleNew) ops.push({ type: 'add', text });
  } else {
    ops.push(...lcsDiff(middleOld, middleNew));
  }

  for (let index = oldEnd; index < oldLines.length; index++) {
    ops.push({ type: 'equal', text: oldLines[index] });
  }

  return ops;
}

/**
 * Groups the edit script into hunks, keeping `context` lines around each change.
 *
 * @param {{ type: 'equal' | 'add' | 'del', text: string }[]} ops
 * @param {number} context - Amount of context lines.
 * @returns {Hunk[]}
 */
function buildHunks(ops, context) {
  let oldLine = 0;
  let newLine = 0;

  /** @type {DiffLine[]} */
  const annotated = ops.map((op) => {
    /** @type {DiffLine} */
    const entry = {
      type: op.type,
      text: truncate(op.text, MAX_DIFF_LINE_LENGTH),
      oldLine: op.type === 'add' ? 0 : ++oldLine,
      newLine: op.type === 'del' ? 0 : ++newLine,
    };

    return entry;
  });

  const keep = new Array(annotated.length).fill(false);

  annotated.forEach((entry, index) => {
    if (entry.type === 'equal') return;

    const from = Math.max(0, index - context);
    const to = Math.min(annotated.length - 1, index + context);

    for (let cursor = from; cursor <= to; cursor++) keep[cursor] = true;
  });

  /** @type {Hunk[]} */
  const hunks = [];
  /** @type {DiffLine[] | null} */
  let current = null;

  annotated.forEach((entry, index) => {
    if (!keep[index]) {
      current = null;
      return;
    }

    if (!current) {
      current = [];
      hunks.push({ oldStart: 0, oldCount: 0, newStart: 0, newCount: 0, lines: current });
    }

    current.push(entry);
  });

  for (const hunk of hunks) {
    const oldLines = hunk.lines.filter((line) => line.type !== 'add');
    const newLines = hunk.lines.filter((line) => line.type !== 'del');

    hunk.oldCount = oldLines.length;
    hunk.newCount = newLines.length;
    hunk.oldStart = oldLines.length > 0 ? oldLines[0].oldLine : 0;
    hunk.newStart = newLines.length > 0 ? newLines[0].newLine : 0;
  }

  return hunks;
}

/**
 * Builds the line based diff of two text files.
 *
 * @param {string} distPath
 * @param {string} referencePath
 * @param {number} contextLines
 * @returns {Promise<TextDifference>}
 */
async function describeTextDifference(distPath, referencePath, contextLines) {
  const [distText, referenceText] = await Promise.all([
    fs.readFile(distPath, 'utf8'),
    fs.readFile(referencePath, 'utf8'),
  ]);

  const ops = computeLineDiff(splitLines(distText), splitLines(referenceText));

  return {
    kind: 'text',
    hunks: buildHunks(ops, contextLines),
    added: ops.filter((op) => op.type === 'add').length,
    removed: ops.filter((op) => op.type === 'del').length,
  };
}

/**
 * Finds the offset of the first byte that differs between two files.
 *
 * @param {string} firstPath
 * @param {string} secondPath
 * @returns {Promise<number>} The offset or -1 when both files are identical.
 */
async function findFirstDifference(firstPath, secondPath) {
  const [first, second] = await Promise.all([fs.open(firstPath, 'r'), fs.open(secondPath, 'r')]);

  try {
    const firstBuffer = Buffer.allocUnsafe(CHUNK_SIZE);
    const secondBuffer = Buffer.allocUnsafe(CHUNK_SIZE);
    let offset = 0;

    for (;;) {
      const [firstRead, secondRead] = await Promise.all([
        first.read(firstBuffer, 0, CHUNK_SIZE, offset),
        second.read(secondBuffer, 0, CHUNK_SIZE, offset),
      ]);

      const comparable = Math.min(firstRead.bytesRead, secondRead.bytesRead);

      for (let index = 0; index < comparable; index++) {
        if (firstBuffer[index] !== secondBuffer[index]) return offset + index;
      }

      if (firstRead.bytesRead !== secondRead.bytesRead) return offset + comparable;
      if (firstRead.bytesRead === 0) return -1;

      offset += firstRead.bytesRead;
    }
  } finally {
    await Promise.all([first.close(), second.close()]);
  }
}

/**
 * Reads a small window of the file, used to preview the difference.
 *
 * @param {string} absolutePath
 * @param {number} offset
 * @param {number} length
 * @returns {Promise<Buffer>
 */
async function readWindow(absolutePath, offset, length) {
  if (length <= 0) return Buffer.alloc(0);

  const handle = await fs.open(absolutePath, 'r');

  try {
    const buffer = Buffer.alloc(length);
    const { bytesRead } = await handle.read(buffer, 0, length, offset);
    return buffer.subarray(0, bytesRead);
  } finally {
    await handle.close();
  }
}

/**
 * Resolves the line/column of a byte offset and returns the line content.
 *
 * @param {string} absolutePath
 * @param {number} offset
 * @returns {Promise<{ line: number, column: number, text: string | null }>}
 */
async function locate(absolutePath, offset) {
  const handle = await fs.open(absolutePath, 'r');

  try {
    const buffer = Buffer.allocUnsafe(CHUNK_SIZE);
    let position = 0;
    let line = 1;
    let lineStart = 0;

    while (position < offset) {
      const { bytesRead } = await handle.read(
        buffer,
        0,
        Math.min(CHUNK_SIZE, offset - position),
        position,
      );

      if (bytesRead === 0) break;

      for (let index = 0; index < bytesRead; index++) {
        if (buffer[index] === 0x0a) {
          line += 1;
          lineStart = position + index + 1;
        }
      }

      position += bytesRead;
    }

    const text = await readLine(handle, lineStart);

    return { line, column: offset - lineStart + 1, text };
  } finally {
    await handle.close();
  }
}

/**
 * Reads a single line starting at the given offset.
 *
 * @param {import('node:fs/promises').FileHandle} handle
 * @param {number} start - Byte offset where the line starts.
 * @returns {Promise<string | null>}
 */
async function readLine(handle, start) {
  const buffer = Buffer.allocUnsafe(4096);
  const { bytesRead } = await handle.read(buffer, 0, buffer.length, start);

  if (bytesRead === 0) return '';

  const chunk = buffer.subarray(0, bytesRead);
  const newLine = chunk.indexOf(0x0a);
  const line = newLine === -1 ? chunk : chunk.subarray(0, newLine);

  return truncate(line.toString('utf8'));
}

/**
 * Builds the hexadecimal description used for binary files.
 *
 * @param {string} distPath
 * @param {string} referencePath
 * @param {number} context - Amount of bytes shown before/after the difference.
 * @param {string} reason - Why the file was treated as binary.
 * @returns {Promise<BinaryDifference | null>}
 */
async function describeBinaryDifference(distPath, referencePath, context, reason) {
  const offset = await findFirstDifference(distPath, referencePath);

  if (offset === -1) return null;

  const start = Math.max(0, offset - context);
  const length = context * 2 + 1;

  const [distWindow, referenceWindow, distLocation, referenceLocation] = await Promise.all([
    readWindow(distPath, start, length),
    readWindow(referencePath, start, length),
    locate(distPath, offset),
    locate(referencePath, offset),
  ]);

  return {
    kind: 'binary',
    offset,
    reason,
    dist: {
      line: distLocation.line,
      column: distLocation.column,
      preview: formatBuffer(distWindow),
      lineText: distLocation.text,
    },
    reference: {
      line: referenceLocation.line,
      column: referenceLocation.column,
      preview: formatBuffer(referenceWindow),
      lineText: referenceLocation.text,
    },
  };
}

/**
 * Decides how the difference should be described: a line based diff for text
 * files, a hexadecimal preview for real binaries.
 *
 * @param {FileEntry} distFile
 * @param {FileEntry} referenceFile
 * @param {Options} options
 * @returns {Promise<DifferenceDetail | null>}
 */
async function describeDifference(distFile, referenceFile, options) {
  const [distHead, referenceHead] = await Promise.all([
    readHead(distFile.absolute),
    readHead(referenceFile.absolute),
  ]);

  if (isBinaryBuffer(distHead) || isBinaryBuffer(referenceHead)) {
    return describeBinaryDifference(
      distFile.absolute,
      referenceFile.absolute,
      options.context,
      'binary content',
    );
  }

  const tooBig = distFile.size > MAX_TEXT_SIZE || referenceFile.size > MAX_TEXT_SIZE;

  if (tooBig) {
    return describeBinaryDifference(
      distFile.absolute,
      referenceFile.absolute,
      options.context,
      `file larger than ${formatBytes(MAX_TEXT_SIZE)}`,
    );
  }

  return describeTextDifference(distFile.absolute, referenceFile.absolute, options.contextLines);
}

/**
 * Renders the hunks of a text diff.
 *
 * @param {Hunk[]} hunks
 * @param {(color: keyof typeof COLORS, value: string) => string} paint
 * @returns {string[]}
 */
function renderHunks(hunks, paint) {
  /** @type {string[]} */
  const output = [];

  for (const hunk of hunks) {
    output.push(
      paint(
        'cyan',
        `    @@ -${hunk.oldStart},${hunk.oldCount} +${hunk.newStart},${hunk.newCount} @@`,
      ),
    );

    for (const line of hunk.lines) {
      if (line.type === 'equal') {
        output.push(paint('dim', `       ${String(line.oldLine).padStart(5)} | ${line.text}`));
      } else if (line.type === 'del') {
        output.push(paint('red', `     - ${String(line.oldLine).padStart(5)} | ${line.text}`));
      } else {
        output.push(paint('green', `     + ${String(line.newLine).padStart(5)} | ${line.text}`));
      }
    }
  }

  return output;
}

/**
 * Runs the tasks with a limited amount of parallel executions.
 *
 * @template T, R
 * @param {T[]} items
 * @param {number} limit
 * @param {(item: T) => Promise<R>} worker
 * @returns {Promise<R[]>}
 */
async function mapLimit(items, limit, worker) {
  /** @type {R[]} */
  const results = new Array(items.length);
  let cursor = 0;

  const runners = Array.from({ length: Math.min(limit, items.length) }, async () => {
    for (;;) {
      const index = cursor++;
      if (index >= items.length) return;
      results[index] = await worker(items[index]);
    }
  });

  await Promise.all(runners);

  return results;
}

/**
 * @param {Options} options
 * @returns {Promise<number>} The exit code.
 */
async function main(options) {
  const paint = createPainter(options.color);
  const distDir = path.resolve(options.dist);
  const referenceDir = path.resolve(options.reference);

  const [distStats, referenceStats] = await Promise.all([
    fs.stat(distDir).catch(() => null),
    fs.stat(referenceDir).catch(() => null),
  ]);

  if (!distStats?.isDirectory()) usageError(`Build folder not found: ${distDir}`);
  if (!referenceStats?.isDirectory()) usageError(`Reference folder not found: ${referenceDir}`);

  const ignore = options.ignore.map(globToRegExp);
  const [distFiles, referenceFiles] = await Promise.all([
    listFiles(distDir, ignore),
    listFiles(referenceDir, ignore),
  ]);

  const relativePaths = [...new Set([...distFiles.keys(), ...referenceFiles.keys()])].sort((a, b) =>
    a.localeCompare(b),
  );

  const results = await mapLimit(relativePaths, options.concurrency, async (relative) => {
    const distFile = distFiles.get(relative);
    const referenceFile = referenceFiles.get(relative);

    if (!referenceFile) {
      return /** @type {FileResult} */ ({
        relative,
        status: STATUS.missingInReference,
        dist: distFile,
      });
    }

    if (!distFile) {
      return /** @type {FileResult} */ ({
        relative,
        status: STATUS.missingInDist,
        reference: referenceFile,
      });
    }

    const [distHash, referenceHash] = await Promise.all([
      hashFile(distFile.absolute, options.algorithm),
      hashFile(referenceFile.absolute, options.algorithm),
    ]);

    if (distHash === referenceHash) {
      return /** @type {FileResult} */ ({
        relative,
        status: STATUS.identical,
        dist: distFile,
        reference: referenceFile,
        distHash,
        referenceHash,
      });
    }

    const detail = options.diff ? await describeDifference(distFile, referenceFile, options) : null;

    return /** @type {FileResult} */ ({
      relative,
      status: STATUS.different,
      dist: distFile,
      reference: referenceFile,
      distHash,
      referenceHash,
      detail: detail ?? undefined,
    });
  });

  const summary = {
    dist: distDir,
    reference: referenceDir,
    algorithm: options.algorithm,
    total: results.length,
    identical: results.filter((result) => result.status === STATUS.identical).length,
    different: results.filter((result) => result.status === STATUS.different).length,
    missingInReference: results.filter((result) => result.status === STATUS.missingInReference)
      .length,
    missingInDist: results.filter((result) => result.status === STATUS.missingInDist).length,
  };

  const problems = results.filter((result) => result.status !== STATUS.identical);

  if (options.json) {
    console.log(JSON.stringify({ summary, files: results }, null, 2));
    return problems.length === 0 ? 0 : 1;
  }

  if (!options.quiet) {
    console.log(`${paint('cyan', '[hash-check]')} dist:      ${distDir}`);
    console.log(`${paint('cyan', '[hash-check]')} reference: ${referenceDir}`);
    console.log(`${paint('cyan', '[hash-check]')} algorithm: ${options.algorithm}`);

    if (options.includeMinJs) {
      console.log(`${paint('cyan', '[hash-check]')} min.js:    included`);
    } else {
      console.log(
        `${paint('cyan', '[hash-check]')} min.js:    ignored (${DEFAULT_IGNORE_DESCRIPTION})`,
      );
    }

    console.log('');
  }

  for (const result of problems) {
    if (result.status === STATUS.missingInReference) {
      console.log(`${paint('yellow', '✖')} ${paint('bold', result.relative)}`);
      console.log(
        `    ${paint('yellow', 'only exists in the build folder')} (not found in the reference)`,
      );
      continue;
    }

    if (result.status === STATUS.missingInDist) {
      console.log(`${paint('yellow', '✖')} ${paint('bold', result.relative)}`);
      console.log(
        `    ${paint('yellow', 'missing in the build folder')} (exists in the reference)`,
      );
      continue;
    }

    console.log(`${paint('red', '✖')} ${paint('bold', result.relative)}`);
    console.log(
      `    size:  ${formatBytes(result.dist?.size ?? 0)} (build) vs ${formatBytes(
        result.reference?.size ?? 0,
      )} (reference)`,
    );
    console.log(
      `    hash:  ${result.distHash?.slice(0, 16)} (build) vs ${result.referenceHash?.slice(
        0,
        16,
      )} (reference)`,
    );

    if (result.detail?.kind === 'text') {
      const { hunks, added, removed } = result.detail;

      console.log(
        `    diff:  ${paint('green', `+${added}`)} ${paint('red', `-${removed}`)} in ${
          hunks.length
        } hunk(s)`,
      );

      for (const line of renderHunks(hunks, paint)) console.log(line);
    } else if (result.detail) {
      const { offset, dist, reference, reason } = result.detail;

      console.log(`    diff:  binary (${reason})`);
      console.log(`    first difference at byte ${paint('bold', String(offset))}`);
      console.log(
        `    build:     line ${dist.line}, column ${dist.column}  ${paint('dim', dist.preview)}`,
      );
      console.log(
        `    reference: line ${reference.line}, column ${reference.column}  ${paint(
          'dim',
          reference.preview,
        )}`,
      );

      if (dist.lineText !== null && reference.lineText !== null) {
        if (dist.lineText !== reference.lineText) {
          console.log(`    ${paint('green', '-')} ${sanitize(dist.lineText)}`);
          console.log(`    ${paint('red', '+')} ${sanitize(reference.lineText)}`);
        } else {
          console.log(`    ${paint('dim', `line: ${sanitize(dist.lineText)}`)}`);
        }
      }
    }

    console.log('');
  }

  const hasProblems = problems.length > 0;
  const summaryLine = [
    `${summary.total} file(s) compared`,
    `${summary.identical} identical`,
    `${summary.different} different`,
    `${summary.missingInReference} only in build`,
    `${summary.missingInDist} only in reference`,
  ].join(' | ');

  if (hasProblems) {
    console.log(paint('red', `✖ ${summaryLine}`));
    return 1;
  }

  console.log(paint('green', `✔ ${summaryLine}`));
  return 0;
}

let exitCode = 0;

try {
  const options = parseArgs(process.argv.slice(2));

  if (options.help) {
    printHelp();
  } else {
    exitCode = await main(options);
  }
} catch (error) {
  const isUsageError = error instanceof Error && error.name === 'UsageError';
  console.error(
    `${isUsageError ? '' : 'Unexpected error: '}${error instanceof Error ? error.message : error}`,
  );
  if (isUsageError) console.error('\nRun with --help to see the available options.');
  exitCode = 2;
}

process.exitCode = exitCode;
